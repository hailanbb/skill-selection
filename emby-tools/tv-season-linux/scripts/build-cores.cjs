// Build explicit CommonJS factories from the frozen, audited browser-independent modules.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),up=path.join(root,'vendor/upstream');
const manifest=JSON.parse(fs.readFileSync(path.join(up,'snapshot-manifest.json'),'utf8'));
for(const [file,sha] of Object.entries(manifest.files))if(crypto.createHash('sha256').update(fs.readFileSync(path.join(up,file))).digest('hex')!==sha)throw Error('Upstream changed: '+file);
const out=path.join(root,'lib/generated');fs.mkdirSync(out,{recursive:true});
const read=n=>fs.readFileSync(path.join(up,'src',n+'.js'),'utf8');
for(const name of ['cleanup-core','archive-core','repair-state','version-download','transfer-repair','broadcast-audit','download-core']){
 let source=read(name).replace('/* build:repair-state */ null',read('repair-state'));
 // Use the same conservative date boundary as initial inspection in every stage.
 if(name==='broadcast-audit')source=source.replaceAll('e.air_date<=today','e.air_date<today').replaceAll('e.air_date>today','e.air_date>=today').replaceAll('next.air_date>today','next.air_date>=today');
 fs.writeFileSync(path.join(out,name+'.cjs'),'// Generated by scripts/build-cores.cjs.\nmodule.exports = '+source+';\n','utf8');
}
console.log('Verified frozen source; built seven pure factories.');
